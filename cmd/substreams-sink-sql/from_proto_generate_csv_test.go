// TestSchemaHashConsistency ensures schema hash is consistent
func TestSchemaHashConsistency(t *testing.T) {
	logger := zap.NewNop()

	// Create identical schemas
	schema1 := createTestSchema("test")
	schema2 := createTestSchema("test")

	// Create dialects
	dialect1, err := postgres.NewDialectPostgres(schema1, logger)
	require.NoError(t, err)

	dialect2, err := postgres.NewDialectPostgres(schema2, logger)
	require.NoError(t, err)

	// Hashes should be identical
	hash1 := dialect1.SchemaHash()
	hash2 := dialect2.SchemaHash()

	assert.Equal(t, hash1, hash2, "Schema hashes should be identical for same schema")
}

// Helper functions for testing

func createTestSchema(name string) *schema.Schema {
	s := &schema.Schema{
		Name:          name,
		TableRegistry: make(map[string]*schema.Table),
	}

	table := &schema.Table{
		Name: "test_table",
		Columns: []*schema.Column{
			{
				Name:            "id",
				IsPrimaryKey:    true,
				FieldDescriptor: createTestFieldDescriptor("id", descriptor.FieldDescriptorProto_TYPE_INT64),
			},
		},
	}

	s.TableRegistry["test_table"] = table
	return s
}

func createTestFieldDescriptor(name string, fieldType descriptor.FieldDescriptorProto_Type) *desc.FieldDescriptor {
	// Create a minimal field descriptor proto
	fdp := &descriptor.FieldDescriptorProto{
		Name:   &name,
		Number: proto.Int32(1),
		Type:   &fieldType,
	}

	// Create a minimal message descriptor proto to contain the field
	mdp := &descriptor.DescriptorProto{
		Name:  proto.String("TestMessage"),
		Field: []*descriptor.FieldDescriptorProto{fdp},
	}

	// Create a minimal file descriptor proto
	fileName := "test.proto"
	fdProto := &descriptor.FileDescriptorProto{
		Name:        &fileName,
		MessageType: []*descriptor.DescriptorProto{mdp},
	}

	// Create the file descriptor
	fd, err := desc.CreateFileDescriptor(fdProto)
	if err != nil {
		return nil
	}

	// Get the message descriptor and then the field descriptor
	msgDesc := fd.GetMessageTypes()[0]
	if msgDesc != nil && len(msgDesc.GetFields()) > 0 {
		return msgDesc.GetFields()[0]
	}

	return nil
}
